import type { Episode, Media } from '@automedia/shared'

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

function tag(name: string, value: string | number | null | undefined): string {
  if (value === null || value === undefined || value === '') return ''
  return `  <${name}>${esc(String(value))}</${name}>\n`
}

/**
 * 一集漫画的 ComicInfo.xml（Anansi Project 的 ComicInfo 2.0 格式，放在 cbz 的根目录）。
 * 元素顺序按 XSD 里的顺序写，有些读取方是按 schema 校验的。
 *
 * 字段对应：Series = 漫画标题，Number = 集号，Volume = 季号，Title = 集标题，
 * Writer = 「作者」（存在 studios 字段里），Genre = 类型标签。
 */
export function comicInfoXml(o: {
  media: Media
  season: number
  episode: number
  ep: Episode | undefined
  /** 这一季一共有多少集（已知的），0 表示不写 */
  count: number
  /** 是否写 Volume：只有一季时不写，免得读取方把它显示成「第 1 卷」 */
  withVolume: boolean
  pageCount: number
}): string {
  const { media, ep } = o
  const date = /^(\d{4})(?:-(\d{1,2}))?(?:-(\d{1,2}))?/.exec(ep?.airDate ?? '')
  const year = date ? Number(date[1]) : media.year
  let pages = ''
  for (let i = 0; i < o.pageCount; i++) pages += `    <Page Image="${i}"${i === 0 ? ' Type="FrontCover"' : ''} />\n`

  return (
    '<?xml version="1.0" encoding="utf-8"?>\n' +
    '<ComicInfo xmlns:xsd="http://www.w3.org/2001/XMLSchema" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">\n' +
    tag('Title', ep?.title.trim()) +
    tag('Series', media.title) +
    tag('Number', o.episode) +
    tag('Count', o.count || null) +
    tag('Volume', o.withVolume ? o.season : null) +
    tag('Summary', ep?.overview.trim() || media.overview.trim()) +
    tag('Notes', 'Generated by automedia') +
    tag('Year', year) +
    tag('Month', date?.[2] ? Number(date[2]) : null) +
    tag('Day', date?.[3] ? Number(date[3]) : null) +
    tag('Writer', media.studios.join(', ')) +
    tag('Genre', media.genres.join(', ')) +
    tag('PageCount', o.pageCount) +
    (pages ? `  <Pages>\n${pages}  </Pages>\n` : '') +
    '</ComicInfo>\n'
  )
}
